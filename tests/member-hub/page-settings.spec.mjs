import { test, expect } from '@playwright/test';
import { seedAdmin, localAdmin } from '../../scripts/member-hub/local.mjs';

test('Page Settings follows Preview, preserves unsaved content, and hides slug and metadata from split view', async ({ page }, info) => {
  test.setTimeout(120000);
  const { service } = await seedAdmin();
  const title = `Page Settings Fixture ${Date.now()}`;
  let id;
  try {
    await page.goto('/admin-sign-in');
    await page.getByLabel('Email', { exact: true }).fill(localAdmin.email);
    await page.getByLabel('Password', { exact: true }).fill(localAdmin.password);
    await page.getByRole('button', { name: 'Sign In', exact: true }).click(); await expect(page).toHaveURL(/\/admin\/content$/);
    await page.goto('/admin/content/new');
    await page.setViewportSize({ width: 1920, height: 1080 });
    await expect(page.getByRole('group', { name: 'Content view' }).getByRole('button')).toHaveText(['Edit', 'Side by Side', 'Preview', 'Page Settings']);
    await page.getByLabel('Title', { exact: true }).fill(title);
    const body = page.locator('[contenteditable="true"][aria-label="Page Body"]');
    await body.click(); await body.pressSequentially('Unsaved content before settings.');
    await page.getByRole('button', { name: 'Page Settings', exact: true }).click();
    const preview = page.getByRole('region', { name: 'Content preview', exact: true });
    const previewFrame = page.frameLocator('iframe[title="Page preview"]');
    await expect(previewFrame.getByRole('heading', { name: title, exact: true })).toBeVisible();
    await expect(previewFrame.getByText('Unsaved content before settings.', { exact: true })).toBeVisible();
    await expect(page.getByRole('group', { name: 'Page Settings', exact: true })).toBeVisible();
    await expect(page.getByLabel('Slug', { exact: true })).toHaveCount(0);
    await expect(body).toHaveCount(0);
    await page.getByLabel('Content Type', { exact: true }).selectOption('event');
    await expect(page.getByRole('heading', { name: 'Event Details', exact: true })).toBeVisible();
    await page.getByLabel('Location', { exact: true }).fill('Cypressdale Park');
    await expect(previewFrame.getByText('Cypressdale Park', { exact: true })).toBeVisible();
    await page.getByLabel('Start (Central Time)', { exact: true }).fill('2026-12-01T18:00');
    await page.getByLabel('Members Only', { exact: true }).check();
    await expect(previewFrame.getByText('Members Only', { exact: true })).toBeVisible();
    await page.getByLabel('Page Width', { exact: true }).selectOption('narrow');
    await expect(previewFrame.locator('.max-w-2xl')).toHaveCount(1);
    await page.getByLabel('Page Width', { exact: true }).selectOption('wide');
    await expect(previewFrame.locator('.max-w-5xl')).toHaveCount(1);
    await page.getByLabel('Community Sidebar', { exact: true }).check();
    await expect(previewFrame.getByRole('heading', { name: 'Community', exact: true })).toBeVisible();
    await page.getByLabel('Calendar', { exact: true }).check();
    await page.getByLabel('Email Newsletter Signup', { exact: true }).check();
    await expect(previewFrame.getByRole('heading', { name: 'Calendar', exact: true })).toBeVisible();
    await expect(previewFrame.getByRole('heading', { name: 'Cypressdale Email Newsletter', exact: true })).toBeVisible();
    await page.getByLabel('Calendar', { exact: true }).uncheck();
    await expect(previewFrame.getByRole('heading', { name: 'Calendar', exact: true })).toHaveCount(0);
    await expect(previewFrame.getByRole('heading', { name: 'Community', exact: true })).toBeVisible();
    await expect(previewFrame.getByRole('heading', { name: 'Cypressdale Email Newsletter', exact: true })).toBeVisible();
    await page.getByLabel('Community Sidebar', { exact: true }).uncheck();
    await expect(previewFrame.getByRole('heading', { name: 'Community', exact: true })).toHaveCount(0);
    const image = await service.from('hoa_assets').select('id').like('mime_type', 'image/%').order('id').limit(1).single();
    expect(image.error).toBeNull();
    await page.getByLabel('Flyer', { exact: true }).selectOption(image.data.id);
    await expect.poll(() => previewFrame.locator('img').first().evaluate(element => element.complete && element.naturalWidth > 0)).toBe(true);
    const controls = await page.getByRole('group', { name: 'Page Settings', exact: true }).boundingBox();
    const viewing = await preview.boundingBox();
    expect(controls.x + controls.width).toBeLessThanOrEqual(viewing.x);
    expect(Math.abs(controls.y - viewing.y)).toBeLessThan(2);
    await page.getByRole('group', { name: 'Page Settings', exact: true }).evaluate(element => element.scrollTop = 0);
    const settingsBounds = await page.getByRole('group', { name: 'Page Settings', exact: true }).boundingBox();
    const firstInput = await page.getByLabel('Content Type', { exact: true }).boundingBox();
    expect(firstInput.x - settingsBounds.x).toBeGreaterThanOrEqual(16);
    expect(firstInput.x + firstInput.width).toBeLessThan(settingsBounds.x + settingsBounds.width - 12);
    await page.screenshot({ path: info.outputPath('page-settings-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const mobileControls = await page.getByRole('group', { name: 'Page Settings', exact: true }).boundingBox();
    const mobilePreview = await preview.boundingBox();
    expect(mobilePreview.y).toBeGreaterThanOrEqual(mobileControls.y + mobileControls.height);
    const mobileInput = await page.getByLabel('Content Type', { exact: true }).boundingBox();
    expect(mobileInput.x - mobileControls.x).toBeGreaterThanOrEqual(16);
    expect(mobileInput.x + mobileInput.width).toBeLessThan(mobileControls.x + mobileControls.width - 12);
    await page.screenshot({ path: info.outputPath('page-settings-mobile.png'), fullPage: true });
    await page.getByRole('button', { name: 'Side by Side', exact: true }).click();
    await expect(body).toHaveText('Unsaved content before settings.');
    await expect(page.getByLabel('Content Type', { exact: true })).toHaveCount(0);
    await expect(page.getByLabel('Page Width', { exact: true })).toHaveCount(0);
    await expect(page.getByRole('heading', { name: 'Event Details', exact: true })).toHaveCount(0);
    await expect(previewFrame.getByText('Cypressdale Park', { exact: true })).toBeVisible();
    await expect(previewFrame.getByText('Members Only', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Page Settings', exact: true }).click();
    await expect(page.getByLabel('Location', { exact: true })).toHaveValue('Cypressdale Park');
    await expect(page.getByLabel('Page Width', { exact: true })).toHaveValue('wide');
    await page.getByRole('button', { name: 'Save Changes', exact: true }).click();
    await expect(page.locator('main').getByRole('status')).toContainText('Page saved');
    await expect(page).toHaveURL(/\/admin\/content\/[0-9a-f-]{36}$/);
    id = new URL(page.url()).pathname.split('/').at(-1);
    const saved = await service.from('hoa_content').select('title,settings,visibility,body,slug').eq('id', id).single();
    expect(saved.data.title).toBe(title); expect(saved.data.visibility).toBe('members');
    expect(saved.data.settings.location).toBe('Cypressdale Park'); expect(saved.data.settings.layoutVariant).toBe('wide');
    expect(saved.data.body[0].children[0].text).toBe('Unsaved content before settings.');
    expect(saved.data.slug).toBeNull();
    expect(saved.data.settings.showCalendar).toBe(false);
    expect(saved.data.settings.showNewsletterSignup).toBe(true);
    expect(saved.data.settings.showRightSidebar).toBe(false);
    await page.reload();
    await page.getByRole('button', { name: 'Page Settings', exact: true }).click();
    await expect(page.getByLabel('Email Newsletter Signup', { exact: true })).toBeChecked();
    await expect(page.getByLabel('Calendar', { exact: true })).not.toBeChecked();
  } finally {
    if (!id) id = (await service.from('hoa_content').select('id').eq('title', title).maybeSingle()).data?.id;
    if (id) await service.from('hoa_content').delete().eq('id', id);
  }
});
