import { test, expect } from '@playwright/test';
import { randomUUID, createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { seedAdmin, localAdmin } from '../../scripts/member-hub/local.mjs';

test('desktop and mobile preview modes use real responsive viewports and preserve unsaved edits', async ({ page }, info) => {
  const { service } = await seedAdmin(), id = `preview-device-${randomUUID()}`;
  const assetId = `${id}-image`, objectPath = `tests/${assetId}.jpg`;
  const image = await readFile(new URL('../../public/images/entrance.jpg', import.meta.url));
  const title = 'Community preview devices';
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  try {
    expect((await service.storage.from('hoa-content').upload(objectPath, image, { contentType: 'image/jpeg' })).error).toBeNull();
    expect((await service.from('hoa_assets').insert({ id: assetId, object_path: objectPath, original_filename: 'Preview image.jpg', mime_type: 'image/jpeg', size_bytes: image.length, sha256: createHash('sha256').update(image).digest('hex') })).error).toBeNull();
    expect((await service.from('hoa_content').insert({ id, kind: 'post', title, status: 'draft', visibility: 'public',
      settings: { showNewsletterSignup: true, showCalendar: true }, sections: [{ _type: 'fileSection', _key: 'flyer', file: { asset: { _ref: assetId } } }] })).error).toBeNull();
    expect((await service.from('hoa_content_assets').insert({ content_id: id, asset_id: assetId })).error).toBeNull();
    await page.setViewportSize({ width: 1920, height: 1080 });
    await page.goto('/admin-sign-in');
    await page.getByLabel('Email', { exact: true }).fill(localAdmin.email);
    await page.getByLabel('Password', { exact: true }).fill(localAdmin.password);
    await page.getByRole('button', { name: 'Sign In', exact: true }).click();
    await expect(page).toHaveURL(/\/admin\/content$/);
    await page.goto(`/admin/content/${id}`);
    await page.getByRole('textbox', { name: 'Page Body', exact: true }).fill('Unsaved content stays while changing devices.');
    await page.getByRole('button', { name: 'Side by Side', exact: true }).click();
    const controls = page.getByRole('group', { name: 'Preview device', exact: true });
    const frame = page.locator('iframe[title="Page preview"]');
    const preview = page.frameLocator('iframe[title="Page preview"]');
    const columns = () => preview.locator('article').evaluate(element => getComputedStyle(element.parentElement).gridTemplateColumns.split(' ').length);
    const viewportWidth = () => frame.evaluate(element => element.contentWindow.innerWidth);
    const stage = page.locator('.hub-preview-stage');
    await expect(controls.getByRole('button', { name: 'Desktop preview', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await expect.poll(viewportWidth).toBe(1280);
    await expect.poll(columns).toBe(2);
    await expect(preview.getByText('Unsaved content stays while changing devices.', { exact: true })).toBeVisible();
    const flyer = preview.getByRole('img');
    await expect.poll(() => flyer.evaluate(element => element.complete && element.naturalWidth > 0)).toBe(true);
    await page.screenshot({ path: info.outputPath('desktop-split.png'), fullPage: true });
    await controls.getByRole('button', { name: 'Mobile preview', exact: true }).click();
    await expect.poll(viewportWidth).toBe(390);
    await expect.poll(columns).toBe(1);
    await expect(controls.getByRole('button', { name: 'Mobile preview', exact: true })).toHaveAttribute('aria-pressed', 'true');
    expect(await preview.locator('body').evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('mobile-split.png'), fullPage: true });
    await page.getByRole('button', { name: 'Page Settings', exact: true }).click();
    await expect.poll(viewportWidth).toBe(390);
    await page.getByLabel('Email Newsletter Signup', { exact: true }).uncheck();
    await expect(preview.getByRole('heading', { name: 'Cypressdale Email Newsletter', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Preview', exact: true }).click();
    await expect.poll(viewportWidth).toBe(390);
    const phoneBounds = await frame.boundingBox(), stageBounds = await stage.boundingBox();
    expect(Math.abs((phoneBounds.x - stageBounds.x) - (stageBounds.width - phoneBounds.width) / 2)).toBeLessThan(2);
    await page.screenshot({ path: info.outputPath('mobile-full-preview.png'), fullPage: true });
    await controls.getByRole('button', { name: 'Desktop preview', exact: true }).click();
    await expect.poll(viewportWidth).toBeGreaterThan(1280);
    await expect.poll(columns).toBe(2);
    await page.screenshot({ path: info.outputPath('desktop-full-preview.png'), fullPage: true });
    await controls.getByRole('button', { name: 'Mobile preview', exact: true }).click();
    await page.getByRole('button', { name: 'Edit', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Page Body', exact: true })).toHaveText('Unsaved content stays while changing devices.');
    await page.getByRole('button', { name: 'Side by Side', exact: true }).click();
    await expect.poll(viewportWidth).toBe(390);
    await page.setViewportSize({ width: 390, height: 844 });
    await expect.poll(() => frame.evaluate(element => element.getBoundingClientRect().width <= element.closest('.hub-preview-stage').clientWidth + 1)).toBe(true);
    await expect.poll(viewportWidth).toBe(390);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('mobile-preview-small-screen.png'), fullPage: true });
    await controls.getByRole('button', { name: 'Desktop preview', exact: true }).click();
    await expect.poll(viewportWidth).toBe(1280);
    await expect.poll(columns).toBe(2);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const stored = (await service.from('hoa_content').select('body,status,settings').eq('id', id).single()).data;
    expect(stored.body).toEqual([]); expect(stored.status).toBe('draft'); expect(stored.settings.showNewsletterSignup).toBe(true);
    expect(errors).toEqual([]);
  } finally {
    await service.from('hoa_content').delete().eq('id', id);
    await service.from('hoa_assets').delete().eq('id', assetId);
    await service.storage.from('hoa-content').remove([objectPath]);
  }
});
