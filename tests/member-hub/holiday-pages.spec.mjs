import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { seedAdmin, localAdmin } from '../../scripts/member-hub/local.mjs';

test('public holiday navigation and admin text links keep entries and settings separate', async ({ page, context, request }, info) => {
  test.setTimeout(120000);
  const { service } = await seedAdmin();
  const prefix = `Holiday Split Fixture ${randomUUID()}`;
  const fixtures = [['christmas', 2099], ['halloween', 2099], ['halloween', 2098]].map(([holiday, year]) => ({
    id: `holiday-split-${randomUUID()}`, kind: 'holidayWinner', title: `${prefix} ${holiday} ${year}`,
    status: 'published', visibility: 'public', settings: { holiday, year, place: '1', photos: [] },
  }));
  const before = (await service.from('hoa_content').select('*').eq('id', 'program-halloween-decorating').single()).data;
  const christmasBefore = (await service.from('hoa_content').select('settings').eq('id', 'program-holiday-decorating').single()).data.settings;
  let ownedVersion, createdId;
  const previewPage = await context.newPage();
  try {
    expect((await service.from('hoa_content').insert(fixtures)).error).toBeNull();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto('/holiday-decorating/christmas');
    await expect(page.getByRole('heading', { name: fixtures[0].title, exact: true })).toBeVisible();
    await expect(page.getByRole('navigation', { name: 'Holiday selection', exact: true })).toHaveCount(0);
    const selection = page.getByRole('navigation', { name: 'Main navigation', exact: true });
    const trigger = selection.getByRole('button', { name: 'Holiday Decorating', exact: true });
    await expect(trigger).toHaveAttribute('aria-expanded', 'false');
    await trigger.focus();
    await page.keyboard.press('Enter');
    await expect(selection.getByRole('link', { name: 'Christmas', exact: true })).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(trigger).toBeFocused();
    await expect(trigger).toHaveAttribute('aria-expanded', 'false');
    await trigger.click();
    await page.getByRole('heading', { name: fixtures[0].title, exact: true }).click();
    await expect(trigger).toHaveAttribute('aria-expanded', 'false');
    await trigger.click();
    await page.screenshot({ path: info.outputPath('holiday-desktop-menu.png') });
    await selection.getByRole('link', { name: 'Halloween', exact: true }).click();
    await expect(page).toHaveURL(/\/holiday-decorating\/halloween$/);
    const halloweenBackground = page.locator('div.bg-gradient-to-b.from-orange-900');
    await expect(halloweenBackground).toHaveCount(1);
    expect(await halloweenBackground.evaluate(element => getComputedStyle(element).backgroundImage)).toContain('linear-gradient');
    await expect(page.getByRole('heading', { name: fixtures[1].title, exact: true })).toBeVisible();
    await expect(page.getByRole('heading', { name: fixtures[0].title, exact: true })).toHaveCount(0);
    await page.getByRole('tab', { name: '2098', exact: true }).click();
    await expect(page.getByRole('heading', { name: fixtures[2].title, exact: true })).toBeVisible();
    await page.screenshot({ path: info.outputPath('halloween-public-desktop.png'), fullPage: true });
    await page.reload();
    await trigger.click();
    await expect(selection.getByRole('link', { name: 'Halloween', exact: true })).toHaveAttribute('aria-current', 'page');
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('halloween-public-mobile.png'), fullPage: true });
    await page.getByRole('button', { name: 'Toggle menu', exact: true }).click();
    const mobileSelection = page.getByRole('navigation', { name: 'Mobile navigation', exact: true });
    await mobileSelection.getByRole('button', { name: 'Holiday Decorating', exact: true }).click();
    await page.screenshot({ path: info.outputPath('holiday-mobile-menu.png'), fullPage: true });
    await mobileSelection.getByRole('link', { name: 'Christmas', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Toggle menu', exact: true })).toHaveAttribute('aria-expanded', 'false');
    await expect(page.getByRole('heading', { name: fixtures[0].title, exact: true })).toBeVisible();
    await page.screenshot({ path: info.outputPath('christmas-public-mobile.png'), fullPage: true });
    expect((await request.get('/holiday-decorating/unknown')).status()).toBe(404);
    await page.goto('/admin-sign-in');
    await page.getByLabel('Email', { exact: true }).fill(localAdmin.email);
    await page.getByLabel('Password', { exact: true }).fill(localAdmin.password);
    await page.getByRole('button', { name: 'Sign In', exact: true }).click();
    await expect(page).toHaveURL(/\/admin\/content$/);
    await page.goto('/admin/holiday-decorating/christmas');
    const adminSelection = page.getByRole('navigation', { name: 'Holiday selection', exact: true });
    await expect(adminSelection.getByRole('button', { name: 'Christmas', exact: true })).toHaveText('Christmas');
    await expect(adminSelection.getByRole('button', { name: 'Halloween', exact: true })).toHaveText('Halloween');
    await expect(page.getByRole('button', { name: `Edit ${fixtures[1].title}`, exact: true })).toHaveCount(0);
    await adminSelection.getByRole('button', { name: 'Halloween', exact: true }).click();
    await expect(page).toHaveURL(/\/admin\/holiday-decorating\/halloween$/);
    await expect(page.getByRole('button', { name: `Edit ${fixtures[1].title}`, exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: `Edit ${fixtures[0].title}`, exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'New Winner', exact: true }).click();
    await expect(page.getByLabel('Holiday', { exact: true })).toHaveValue('Halloween');
    await expect(page.getByLabel('Holiday', { exact: true })).toHaveAttribute('readonly', '');
    await page.getByLabel('Winner Title', { exact: true }).fill(`${prefix} New Winner`);
    page.once('dialog', dialog => dialog.dismiss());
    await adminSelection.getByRole('button', { name: 'Christmas', exact: true }).click();
    await expect(page.getByLabel('Winner Title', { exact: true })).toHaveValue(`${prefix} New Winner`);
    await page.getByLabel('Year', { exact: true }).fill('2100');
    await page.getByLabel('Published', { exact: true }).check();
    await page.getByRole('button', { name: 'Save Winner', exact: true }).click();
    await expect(page.locator('main').getByRole('status')).toHaveText('Winner saved.');
    const created = (await service.from('hoa_content').select('id,settings').eq('title', `${prefix} New Winner`).single()).data;
    createdId = created.id; expect(created.settings.holiday).toBe('halloween');
    await page.getByRole('button', { name: 'Page Settings', exact: true }).click();
    await page.getByLabel('Page Title', { exact: true }).fill(`${prefix} Halloween Page`);
    await page.getByRole('button', { name: 'Save Page Settings', exact: true }).click();
    await expect(page.locator('main').getByRole('status')).toHaveText('Page settings saved.');
    ownedVersion = (await service.from('hoa_content').select('version').eq('id', before.id).single()).data.version;
    expect((await service.from('hoa_content').select('settings').eq('id', 'program-holiday-decorating').single()).data.settings).toEqual(christmasBefore);
    await previewPage.goto('/holiday-decorating/halloween');
    await expect(previewPage.getByRole('heading', { name: `${prefix} Halloween Page`, exact: true })).toBeVisible();
    await page.setViewportSize({ width: 1920, height: 1080 });
    await page.screenshot({ path: info.outputPath('holiday-admin-text-switcher.png'), fullPage: true });
    await expect(page.frameLocator('iframe[title="Page preview"]').getByRole('navigation', { name: 'Holiday selection', exact: true })).toHaveCount(0);
    await expect(page.frameLocator('iframe[title="Page preview"]').locator('div.bg-gradient-to-b.from-orange-900')).toHaveCount(1);
    await adminSelection.getByRole('button', { name: 'Christmas', exact: true }).click();
    await expect(page).toHaveURL(/\/admin\/holiday-decorating\/christmas$/);
    await page.goto(`/admin/content/${fixtures[1].id}`);
    await expect(page).toHaveURL(new RegExp(`/admin/holiday-decorating/halloween\\?winner=${fixtures[1].id}$`));
  } finally {
    await previewPage.close();
    if (!createdId) createdId = (await service.from('hoa_content').select('id').eq('title', `${prefix} New Winner`).maybeSingle()).data?.id;
    await service.from('hoa_content').delete().in('id', [...fixtures.map(row => row.id), ...(createdId ? [createdId] : [])]);
    if (ownedVersion) await service.from('hoa_content').update({ title: before.title, settings: before.settings, locally_edited: before.locally_edited }).eq('id', before.id).eq('version', ownedVersion);
  }
});
