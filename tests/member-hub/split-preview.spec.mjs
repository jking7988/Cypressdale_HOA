import { test, expect } from '@playwright/test';
import { seedAdmin, localAdmin } from '../../scripts/member-hub/local.mjs';

test('full-width side-by-side preview stays live and retains unsaved flyer edits', async ({ page }, info) => {
  test.setTimeout(120000);
  const { service } = await seedAdmin();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto('/admin-sign-in');
  await page.getByLabel('Email', { exact: true }).fill(localAdmin.email);
  await page.getByLabel('Password', { exact: true }).fill(localAdmin.password);
  await page.getByRole('button', { name: 'Sign In', exact: true }).click(); await expect(page).toHaveURL(/\/admin\/content$/);
  await page.goto('/admin/content/new');
  await page.getByRole('button', { name: 'Page Settings', exact: true }).click();
  await page.getByLabel('Content Type', { exact: true }).selectOption('event');
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Title', { exact: true }).fill('Live Flyer Preview Fixture');
  const body = page.locator('[contenteditable="true"][aria-label="Page Body"]');
  await body.click(); await body.pressSequentially('Unsaved flyer copy.');
  await page.getByRole('button', { name: 'Side by Side', exact: true }).click();
  const preview = page.getByRole('region', { name: 'Content preview', exact: true });
  const previewFrame = page.frameLocator('iframe[title="Page preview"]');
  await expect(previewFrame.getByRole('heading', { name: 'Live Flyer Preview Fixture', exact: true })).toBeVisible();
  await expect(previewFrame.getByText('Unsaved flyer copy.', { exact: true })).toBeVisible();
  await expect(body).toBeVisible();
  await body.click(); await body.press('End'); await body.pressSequentially(' Added while previewing.');
  await expect(previewFrame.getByText('Unsaved flyer copy. Added while previewing.', { exact: true })).toBeVisible();
  await page.getByLabel('Title', { exact: true }).fill('Updated Flyer Preview Fixture');
  await expect(previewFrame.getByRole('heading', { name: 'Updated Flyer Preview Fixture', exact: true })).toBeVisible();
  const image = await service.from('hoa_assets').select('id').like('mime_type', 'image/%').order('id').limit(1).single();
  expect(image.error).toBeNull();
  await page.getByRole('button', { name: 'Page Settings', exact: true }).click();
  await page.getByLabel('Flyer', { exact: true }).selectOption(image.data.id);
  await page.getByRole('button', { name: 'Side by Side', exact: true }).click();
  await expect.poll(() => previewFrame.locator('img').first().evaluate(element => element.complete && element.naturalWidth > 0)).toBe(true);
  await page.locator('.hub-editor-grid').evaluate(element => element.scrollTop = 0);
  await preview.evaluate(element => element.scrollTop = 0);
  for (const width of [1280, 1920, 2560]) {
    await page.setViewportSize({ width, height: 1080 });
    const workspace = await page.locator('.hub-editor-workspace').boundingBox();
    expect(workspace.width).toBeGreaterThan(width - 80);
    const editing = await page.getByRole('group', { name: 'Content editing controls' }).boundingBox();
    const viewing = await preview.boundingBox();
    expect(editing.x + editing.width).toBeLessThanOrEqual(viewing.x);
    expect(Math.abs(editing.y - viewing.y)).toBeLessThan(2);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await page.screenshot({ path: info.outputPath('split-preview-wide.png'), fullPage: true });
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await expect(previewFrame.getByText('Unsaved flyer copy. Added while previewing.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await expect(body).toHaveText('Unsaved flyer copy. Added while previewing.');
  await page.getByRole('button', { name: 'Side by Side', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  const editing = await page.getByRole('group', { name: 'Content editing controls' }).boundingBox();
  const viewing = await preview.boundingBox();
  expect(viewing.y).toBeGreaterThanOrEqual(editing.y + editing.height);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('split-preview-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
});
